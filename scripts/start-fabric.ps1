#requires -Version 5.1
<#
    start-fabric.ps1

    Keeps the FundEd Hyperledger Fabric network + Hyperledger Explorer running
    inside WSL, so the app's ledger explorer and the "Open on Hyperledger
    Explorer" link (http://localhost:8090) keep working.

    Background: WSL2 terminates the Ubuntu instance shortly after the last
    session/process exits (it calls `systemctl poweroff` under the hood).
    That kills Docker, which kills every Fabric container. The vmIdleTimeout
    setting only stops the VM from shutting down — it does not stop the
    instance from being terminated — so we also pin a persistent WSL session
    running scripts/fabric-stack.sh.

    Usage:
      powershell -ExecutionPolicy Bypass -File scripts\start-fabric.ps1
          Start the stack now and wait until Explorer responds.

      powershell -ExecutionPolicy Bypass -File scripts\start-fabric.ps1 -InstallAutostart
          Register a logon Scheduled Task that starts the stack automatically,
          then start it now. This is the "make it just keep working" option.

      powershell -ExecutionPolicy Bypass -File scripts\start-fabric.ps1 -Stop
          Stop the keep-alive session and terminate WSL (stops Fabric + Explorer).
#>
[CmdletBinding()]
param(
    [string]$Distro = "Ubuntu",
    [switch]$InstallAutostart,
    [switch]$Stop
)

$ErrorActionPreference = "Stop"

# Convert e.g. C:\Users\...\scripts to /mnt/c/Users/.../scripts/fabric-stack.sh
$drive     = $PSScriptRoot.Substring(0, 1).ToLower()
$wslScript = "/mnt/$drive" + ($PSScriptRoot.Substring(2) -replace '\\', '/') + "/fabric-stack.sh"
$wslArgs   = "-d `"$Distro`" -u root -- bash `"$wslScript`""

function Write-Step($msg) { Write-Host "==> $msg" }

function Ensure-IdleTimeout {
    $cfg = Join-Path $env:USERPROFILE ".wslconfig"
    $desired = "vmIdleTimeout=-1"
    if (-not (Test-Path $cfg)) {
        Write-Step "Creating $cfg with $desired"
        Set-Content -Path $cfg -Encoding ASCII -Value @(
            "[wsl2]",
            "# Keep the WSL VM (Fabric + Explorer) from shutting down while idle.",
            $desired
        )
        return
    }
    $content = Get-Content -Raw $cfg
    if ($content -notmatch "vmIdleTimeout\s*=\s*-1") {
        Write-Step "Adding $desired to existing $cfg"
        if ($content -match "vmIdleTimeout\s*=") {
            $content = $content -replace "vmIdleTimeout\s*=\s*.*", $desired
        } else {
            if ($content -notmatch "\[wsl2\]") { $content = "[wsl2]`r`n" + $content }
            $content = $content.TrimEnd() + "`r`n$desired`r`n"
        }
        Set-Content -Path $cfg -Value $content -Encoding ASCII
    }
}

# The keep-alive is "running" if fabric-stack.sh is alive inside WSL. We check
# from inside the distro (the wsl.exe CommandLine isn't reliably readable from
# the Windows side).
function Test-KeepAliveRunning {
    $out = & wsl.exe -d $Distro -u root -- pgrep -f "fabric-stack.sh" 2>$null
    return [bool]$out
}

function Start-KeepAlive {
    if (Test-KeepAliveRunning) {
        Write-Step "Keep-alive session already running."
        return
    }
    Write-Step "Starting pinned WSL session -> bash $wslScript"
    # Launch through WMI so the process is owned by the WMI provider host, not
    # by this shell. That keeps it running even if the invoking shell (or a
    # shell-job/CI wrapper) tears its children down when it exits.
    try {
        $null = Invoke-CimMethod -ClassName Win32_Process -MethodName Create `
            -Arguments @{ CommandLine = "wsl.exe $wslArgs" }
    } catch {
        Start-Process -FilePath "wsl.exe" -ArgumentList $wslArgs -WindowStyle Hidden | Out-Null
    }
    Start-Sleep -Seconds 5
    if (Test-KeepAliveRunning) { Write-Step "Keep-alive session running." }
    else { Write-Warning "Keep-alive session did not start; check /root/funded-fabric/start-stack.log in WSL." }
}

function Get-StartupLauncher {
    Join-Path ([Environment]::GetFolderPath("Startup")) "FundEd Fabric Explorer.vbs"
}

function Install-Autostart {
    # A shortcut script in the user's Startup folder — no admin rights needed
    # (Register-ScheduledTask requires elevation). The VBS launches wsl.exe
    # hidden and exits, leaving the session-holding wsl.exe running.
    $vbs = Get-StartupLauncher
    # Escape embedded double quotes for the VBScript string literal.
    $vbsArgs = $wslArgs -replace '"', '""'
    $line = 'CreateObject("WScript.Shell").Run "wsl.exe ' + $vbsArgs + '", 0, False'
    Write-Step "Installing autostart launcher: $vbs"
    Set-Content -Path $vbs -Value @(
        "' Auto-generated by scripts/start-fabric.ps1 - starts Fabric + Explorer in WSL.",
        $line
    ) -Encoding ASCII
    Write-Step "Autostart installed; it will run the next time you log in."
}

function Stop-Stack {
    $vbs = Get-StartupLauncher
    if (Test-Path $vbs) { Remove-Item -LiteralPath $vbs -Force; Write-Step "Removed autostart launcher." }
    Write-Step "Terminating WSL (stops Fabric + Explorer containers)."
    & wsl.exe --terminate $Distro | Out-Null
}

if ($Stop) { Stop-Stack; return }

Ensure-IdleTimeout

if ($InstallAutostart) { Install-Autostart }
Start-KeepAlive

Write-Step "Waiting for Hyperledger Explorer on http://localhost:8090 ..."
$ok = $false
for ($i = 0; $i -lt 60; $i++) {
    try {
        $r = Invoke-WebRequest -Uri "http://localhost:8090" -UseBasicParsing -TimeoutSec 3
        if ($r.StatusCode -ge 200 -and $r.StatusCode -lt 500) { $ok = $true; break }
    } catch { Start-Sleep -Seconds 3 }
}
if ($ok) { Write-Step "Explorer is reachable: http://localhost:8090" }
else     { Write-Warning "Explorer not reachable yet; it may still be starting. Check: wsl -d $Distro -u root -- docker logs explorer.funded.com" }